package br.com.genosha.metacore.format.image.fixtures;

import java.awt.image.BufferedImage;
import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.ByteBuffer;
import java.nio.charset.StandardCharsets;
import java.util.Arrays;
import java.util.zip.CRC32;
import java.util.zip.Deflater;
import java.util.zip.DeflaterOutputStream;
import javax.imageio.ImageIO;

/**
 * Gera PNGs de teste por código. A imagem base vem do codificador PNG do JDK; os chunks de texto,
 * EXIF e XMP são montados aqui. Todas as fixtures têm 64x48 pixels.
 */
public final class PngFixtures {

  public static final int WIDTH = 64;
  public static final int HEIGHT = 48;

  private PngFixtures() {}

  public static byte[] plain() {
    return baseImage();
  }

  /** {@code tEXt} (Title, Author), {@code zTXt} (Comment) e {@code iTXt} em UTF-8 (Description). */
  public static byte[] withText() {
    return insertAfterIhdr(
        baseImage(),
        tEXt("Title", "Sunset"),
        tEXt("Author", "Genosha"),
        zTXt("Comment", "Generated by MetaCore tests"),
        iTXt("Description", "pt-BR", "Pôr do sol em São Paulo"));
  }

  /** Texto depois dos dados da imagem, onde a especificação também permite. */
  public static byte[] textAfterImageData() {
    return insertBeforeIend(baseImage(), tEXt("Software", "MetaCore"));
  }

  /** EXIF no chunk {@code eXIf}. */
  public static byte[] withExif() {
    return insertAfterIhdr(baseImage(), chunk("eXIf", JpegFixtures.basicExifTiff()));
  }

  /** XMP no chunk {@code iTXt} com a palavra-chave {@code XML:com.adobe.xmp}. */
  public static byte[] withXmp() {
    String packet =
        JpegFixtures.xmpPacket(
            "", "tiff:Make=\"Genosha\" xmp:CreateDate=\"2026-01-02T03:04:05Z\"", "");
    return insertAfterIhdr(baseImage(), iTXt("XML:com.adobe.xmp", "", packet));
  }

  /** {@code zTXt} que descompacta para {@code inflatedBytes} bytes. */
  public static byte[] withCompressionBomb(int inflatedBytes) {
    byte[] text = new byte[inflatedBytes];
    Arrays.fill(text, (byte) 'A');
    return insertAfterIhdr(
        baseImage(), chunk("zTXt", concat(latin1("Comment\0"), new byte[] {0}, deflate(text))));
  }

  public static byte[] truncate(byte[] content, int length) {
    return Arrays.copyOf(content, length);
  }

  private static byte[] tEXt(String keyword, String text) {
    return chunk("tEXt", latin1(keyword + "\0" + text));
  }

  private static byte[] zTXt(String keyword, String text) {
    return chunk(
        "zTXt",
        concat(
            latin1(keyword + "\0"),
            new byte[] {0},
            deflate(text.getBytes(StandardCharsets.ISO_8859_1))));
  }

  private static byte[] iTXt(String keyword, String language, String text) {
    return chunk(
        "iTXt",
        concat(
            latin1(keyword + "\0"),
            new byte[] {0, 0},
            latin1(language + "\0"),
            new byte[] {0},
            text.getBytes(StandardCharsets.UTF_8)));
  }

  /** Chunk completo: tamanho, tipo, dados e CRC. */
  public static byte[] chunk(String type, byte[] data) {
    byte[] typeBytes = type.getBytes(StandardCharsets.US_ASCII);
    CRC32 crc = new CRC32();
    crc.update(typeBytes);
    crc.update(data);
    return ByteBuffer.allocate(12 + data.length)
        .putInt(data.length)
        .put(typeBytes)
        .put(data)
        .putInt((int) crc.getValue())
        .array();
  }

  private static byte[] insertAfterIhdr(byte[] png, byte[]... chunks) {
    int ihdrEnd = 8 + 8 + 13 + 4;
    return concat(
        Arrays.copyOfRange(png, 0, ihdrEnd),
        concat(chunks),
        Arrays.copyOfRange(png, ihdrEnd, png.length));
  }

  private static byte[] insertBeforeIend(byte[] png, byte[]... chunks) {
    int iendStart = png.length - 12;
    return concat(
        Arrays.copyOfRange(png, 0, iendStart),
        concat(chunks),
        Arrays.copyOfRange(png, iendStart, png.length));
  }

  private static byte[] baseImage() {
    BufferedImage image = new BufferedImage(WIDTH, HEIGHT, BufferedImage.TYPE_INT_RGB);
    for (int y = 0; y < HEIGHT; y++) {
      for (int x = 0; x < WIDTH; x++) {
        image.setRGB(x, y, (x * 4) << 16 | (y * 5) << 8 | 0x80);
      }
    }
    ByteArrayOutputStream out = new ByteArrayOutputStream();
    try {
      if (!ImageIO.write(image, "png", out)) {
        throw new IllegalStateException("No PNG writer available");
      }
    } catch (IOException e) {
      throw new UncheckedIOException(e);
    }
    return out.toByteArray();
  }

  private static byte[] deflate(byte[] data) {
    ByteArrayOutputStream out = new ByteArrayOutputStream();
    try (DeflaterOutputStream deflater =
        new DeflaterOutputStream(out, new Deflater(Deflater.BEST_COMPRESSION))) {
      deflater.write(data);
    } catch (IOException e) {
      throw new UncheckedIOException(e);
    }
    return out.toByteArray();
  }

  private static byte[] latin1(String text) {
    return text.getBytes(StandardCharsets.ISO_8859_1);
  }

  private static byte[] concat(byte[]... parts) {
    ByteArrayOutputStream out = new ByteArrayOutputStream();
    for (byte[] part : parts) {
      out.writeBytes(part);
    }
    return out.toByteArray();
  }
}

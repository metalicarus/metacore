package br.com.genosha.metacore.format.image.png;

import static br.com.genosha.metacore.metadata.MetadataKeys.IMAGE_BIT_DEPTH;
import static br.com.genosha.metacore.metadata.MetadataKeys.IMAGE_CAMERA_MAKE;
import static br.com.genosha.metacore.metadata.MetadataKeys.IMAGE_COLOR_TYPE;
import static br.com.genosha.metacore.metadata.MetadataKeys.IMAGE_DATETIME_ORIGINAL;
import static br.com.genosha.metacore.metadata.MetadataKeys.IMAGE_HEIGHT;
import static br.com.genosha.metacore.metadata.MetadataKeys.IMAGE_WIDTH;
import static org.assertj.core.api.Assertions.assertThat;

import br.com.genosha.metacore.api.AnalysisLimits;
import br.com.genosha.metacore.api.ExtractionStatus;
import br.com.genosha.metacore.api.MetadataAnalyzer;
import br.com.genosha.metacore.api.MetadataResult;
import br.com.genosha.metacore.format.image.fixtures.PngFixtures;
import br.com.genosha.metacore.metadata.Metadata;
import br.com.genosha.metacore.metadata.MetadataValue;
import br.com.genosha.metacore.metadata.Warning;
import br.com.genosha.metacore.metadata.WarningCode;
import java.io.ByteArrayInputStream;
import java.time.Duration;
import java.time.OffsetDateTime;
import java.time.ZoneOffset;
import org.junit.jupiter.api.Test;

class PngParserTest {

  private static final MetadataAnalyzer ANALYZER = MetadataAnalyzer.createDefault();

  @Test
  void readsTheHeader() {
    MetadataResult result = analyze(PngFixtures.plain());

    assertThat(result.status()).isEqualTo(ExtractionStatus.SUCCESS);
    assertThat(value(result, IMAGE_WIDTH)).isEqualTo(MetadataValue.of(PngFixtures.WIDTH));
    assertThat(value(result, IMAGE_HEIGHT)).isEqualTo(MetadataValue.of(PngFixtures.HEIGHT));
    assertThat(value(result, IMAGE_BIT_DEPTH)).isEqualTo(MetadataValue.of(8));
    assertThat(value(result, IMAGE_COLOR_TYPE)).isEqualTo(MetadataValue.of("True Color"));
    assertThat(result.find(IMAGE_WIDTH).orElseThrow().namespace()).isEqualTo("PNG:IHDR");
  }

  @Test
  void readsEveryTextChunkAsItsOwnField() {
    MetadataResult result = analyze(PngFixtures.withText());

    assertThat(text(result, "PNG:tEXt", "Title")).isEqualTo("Sunset");
    assertThat(text(result, "PNG:tEXt", "Author")).isEqualTo("Genosha");
    assertThat(text(result, "PNG:zTXt", "Comment")).isEqualTo("Generated by MetaCore tests");
    assertThat(text(result, "PNG:iTXt", "Description")).isEqualTo("Pôr do sol em São Paulo");
  }

  @Test
  void readsTextAfterTheImageData() {
    assertThat(text(analyze(PngFixtures.textAfterImageData()), "PNG:tEXt", "Software"))
        .isEqualTo("MetaCore");
  }

  @Test
  void readsExifFromTheExifChunk() {
    MetadataResult result = analyze(PngFixtures.withExif());

    assertThat(value(result, IMAGE_CAMERA_MAKE)).isEqualTo(MetadataValue.of("Genosha"));
    assertThat(result.find(IMAGE_WIDTH).orElseThrow().namespace()).isEqualTo("PNG:IHDR");
    assertThat(result.warnings()).isEmpty();
  }

  @Test
  void readsXmpFromTheInternationalTextChunk() {
    MetadataResult result = analyze(PngFixtures.withXmp());

    assertThat(value(result, IMAGE_CAMERA_MAKE)).isEqualTo(MetadataValue.of("Genosha"));
    assertThat(value(result, IMAGE_DATETIME_ORIGINAL))
        .isEqualTo(MetadataValue.of(OffsetDateTime.of(2026, 1, 2, 3, 4, 5, 0, ZoneOffset.UTC)));
  }

  @Test
  void skipsCompressedTextBeyondTheLimit() {
    MetadataResult result =
        assertQuick(() -> analyze(PngFixtures.withCompressionBomb(8 * 1024 * 1024)));

    assertThat(result.status()).isEqualTo(ExtractionStatus.PARTIAL);
    assertThat(result.findRaw("PNG:zTXt", "Comment")).isEmpty();
    assertThat(result.warnings())
        .extracting(Warning::code)
        .containsExactly(WarningCode.LIMIT_REACHED);
  }

  @Test
  void compressedTextWithinTheLimitIsRead() {
    MetadataAnalyzer generous =
        MetadataAnalyzer.builder()
            .limits(
                AnalysisLimits.defaults()
                    .withMaxDecompressedTextBytes(16 * 1024 * 1024)
                    .withMaxValueLength(16 * 1024 * 1024))
            .build();

    MetadataResult result =
        generous.analyze(
            new ByteArrayInputStream(PngFixtures.withCompressionBomb(2 * 1024 * 1024)), "a.png");

    assertThat(result.status()).isEqualTo(ExtractionStatus.SUCCESS);
    assertThat(result.findRaw("PNG:zTXt", "Comment")).hasSize(1);
  }

  @Test
  void returnsWhatWasReadBeforeATruncation() {
    byte[] full = PngFixtures.withText();
    MetadataResult result = analyze(PngFixtures.truncate(full, 120));

    assertThat(result.status()).isEqualTo(ExtractionStatus.PARTIAL);
    assertThat(result.find(IMAGE_WIDTH)).isPresent();
    assertThat(text(result, "PNG:tEXt", "Title")).isEqualTo("Sunset");
    assertThat(result.warnings()).extracting(Warning::code).containsExactly(WarningCode.TRUNCATED);
  }

  @Test
  void truncationRightAfterTheSignatureIsPartialWithoutFields() {
    MetadataResult result = analyze(PngFixtures.truncate(PngFixtures.plain(), 9));

    assertThat(result.status()).isEqualTo(ExtractionStatus.PARTIAL);
    assertThat(result.metadata()).isEmpty();
  }

  private static MetadataResult assertQuick(java.util.function.Supplier<MetadataResult> analysis) {
    return org.junit.jupiter.api.Assertions.assertTimeoutPreemptively(
        Duration.ofSeconds(10), analysis::get);
  }

  private static MetadataResult analyze(byte[] content) {
    return ANALYZER.analyze(new ByteArrayInputStream(content), "image.png");
  }

  private static MetadataValue value(MetadataResult result, String key) {
    return result.find(key).orElseThrow(() -> new AssertionError("missing " + key)).value();
  }

  private static String text(MetadataResult result, String namespace, String rawName) {
    return result.findRaw(namespace, rawName).stream()
        .map(Metadata::value)
        .map(v -> ((br.com.genosha.metacore.metadata.TextValue) v).value())
        .findFirst()
        .orElseThrow(() -> new AssertionError("missing " + namespace + "/" + rawName));
  }
}
